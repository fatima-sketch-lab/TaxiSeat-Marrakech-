export function buildSeats(type: 'small' | 'large', occupiedCodes: string[] = [], reservedCodes: string[] = []): Seat[] {
  const templates: Array<{ code: string; position: Seat['position']; label: Seat['label'] }> =
    type === 'small'
      ? [
          { code: 'S1', position: 'front', label: { fr: 'Avant (Passager)', ar: 'الأمام (بجانب السائق)', en: 'Front Passenger' } },
          { code: 'S2', position: 'rear', label: { fr: 'Arrière Gauche', ar: 'الخلف يسار', en: 'Rear Left' } },
          { code: 'S3', position: 'rear', label: { fr: 'Arrière Droite', ar: 'الخلف يمين', en: 'Rear Right' } },
        ]
      : [
          { code: 'S1', position: 'front', label: { fr: 'Avant (Passager)', ar: 'الأمام (بجانب السائق)', en: 'Front Passenger' } },
          { code: 'S2', position: 'middle', label: { fr: 'Rang 2 Gauche', ar: 'الصف 2 يسار', en: 'Row 2 Left' } },
          { code: 'S3', position: 'middle', label: { fr: 'Rang 2 Centre', ar: 'الصف 2 وسط', en: 'Row 2 Center' } },
          { code: 'S4', position: 'middle', label: { fr: 'Rang 2 Droite', ar: 'الصف 2 يمين', en: 'Row 2 Right' } },
          { code: 'S5', position: 'rear', label: { fr: 'Rang 3 Gauche', ar: 'الصف 3 يسار', en: 'Row 3 Left' } },
          { code: 'S6', position: 'rear', label: { fr: 'Rang 3 Droite', ar: 'الصف 3 يمين', en: 'Row 3 Right' } },
        ];

  return templates.map((tpl, idx) => {
    const status = occupiedCodes.includes(tpl.code)
      ? 'occupied'
      : reservedCodes.includes(tpl.code)
      ? 'reserved'
      : 'available';
    return {
      id: `seat_${idx + 1}_${tpl.code}`,
      code: tpl.code,
      position: tpl.position,
      label: tpl.label,
      status,
    };
  });
}

